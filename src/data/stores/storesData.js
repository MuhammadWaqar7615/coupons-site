/**
 * Group stores by their letter.
 * Returns an object like { "#": [...], "A": [...], ... }
 */
export function getStoresByLetter() {
  const grouped = {};
  for (const letter of alphabetLetters) {
    grouped[letter] = stores.filter((s) => s.letter === letter);
  }
  return grouped;
}
